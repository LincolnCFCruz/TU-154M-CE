	passed = get(frame_time)
	sim_start_timer = sim_start_timer + passed
	if sim_start_timer > 0.3 then 
		if notLoaded then reset_switchers() end
		check_controls()
		lamps_eng1()
		lamps_eng2()
		lamps_eng3()
		lamps_fwd()
		small_lamps()
	end
	

	
	

end


